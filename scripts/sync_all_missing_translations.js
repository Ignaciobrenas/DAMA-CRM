// Process each locale file
for (const lang of languages) {
  const filePath = path.join(localesDir, `${lang}.json`);
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  let added = 0;
  for (const [key, trans] of Object.entries(translations)) {
    if (!data[key]) {
      data[key] = trans[lang] || trans['es'] || trans['en'];
      added++;
    }
  }

  // Sort keys alphabetically for clean diffs
  const sorted = {};
  for (const k of Object.keys(data).sort()) {
    sorted[k] = data[k];
  }

  fs.writeFileSync(filePath, JSON.stringify(sorted, null, 2) + '\n', 'utf8');
  console.log(`[${lang.toUpperCase()}] Synchronized ${added} new keys. Total keys: ${Object.keys(sorted).length}`);
}

